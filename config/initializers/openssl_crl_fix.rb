INTERMEDIATE_CERTIFICATES = [
  GODADDY_G2_INTERMEDIATE
].freeze

if OpenSSL::OPENSSL_LIBRARY_VERSION.start_with?("OpenSSL 3.")
  Rails.logger.info "Applying OpenSSL 3.x SSL fixes"

  module OpenSSL
    module X509
      class Store
        alias_method :original_set_default_paths, :set_default_paths

        def set_default_paths
          original_set_default_paths

          INTERMEDIATE_CERTIFICATES.each do |cert_pem|
            begin
              cert = OpenSSL::X509::Certificate.new(cert_pem)
              add_cert(cert)
            rescue OpenSSL::X509::StoreError => e
              # Certificate may already exist in store, ignore duplicates
              raise unless e.message.include?("cert already in hash table")
            rescue OpenSSL::X509::CertificateError => e
              Rails.logger.warn "Failed to parse intermediate certificate: #{e.message}"
            end
          end
        end
      end
    end
  end
end

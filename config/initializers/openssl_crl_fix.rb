# Fix for OpenSSL 3.x SSL certificate verification issues
#
# This initializer addresses two common SSL problems:
#
# 1. CRL checking issue: OpenSSL 3.x has stricter CRL (Certificate Revocation List)
#    checking that can fail when connecting to servers whose certificates have CRL
#    distribution points that can't be reached. This causes "certificate verify failed
#    (unable to get certificate CRL)" errors even though the certificate is valid.
#
# 2. Missing intermediate certificates: Many servers (especially those with GoDaddy
#    certificates) are misconfigured and don't send the complete certificate chain.
#    This causes "unable to get local issuer certificate" errors because Ruby/OpenSSL
#    can't verify the chain without the intermediate certificate(s).
#
# This patch modifies OpenSSL::X509::Store#set_default_paths to also add commonly
# missing intermediate certificates. This ensures all HTTP clients (including HTTParty)
# benefit from the fix regardless of how they create their certificate stores.
#
# See: https://github.com/ruby/openssl/issues/305

